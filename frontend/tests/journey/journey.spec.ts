interface PackFile {
  name: string;
  mimeType: string;
  buffer: Buffer;
}

/** The exact bytes `journey.worker.completions_for` will hash and expect
    among the run's pinned live sources -- generated by calling the same
    `journey.pack` builder the worker calls, never re-implemented here byte
    for byte, so admission and the worker's answer always agree. */
async function packFrom(builder: "journey_pack" | "insufficient_pack"): Promise<PackFile[]> {
  const { stdout } = await execFileAsync(
    PYTHON,
    [
      "-c",
      "import base64, json\n" +
        `from journey.pack import ${builder} as build\n` +
        "print(json.dumps([[n, base64.b64encode(b).decode()] for n, b in build()]))\n",
    ],
    {
      cwd: REPO_ROOT,
      env: {
        ...process.env,
        PYTHONPATH: `${path.join(REPO_ROOT, "tests")}${path.delimiter}${REPO_ROOT}`,
      },
    },
  );
  const rows: [string, string][] = JSON.parse(stdout);
  return rows.map(([name, b64]) => ({
    name,
    mimeType: name.endsWith(".pdf") ? "application/pdf" : "text/plain",
    buffer: Buffer.from(b64, "base64"),
  }));
}

