/** One governed POST from a logged-in page's own session, carrying exactly
    what the workspace's own `fetch` carries: the intent key, and the
    same-origin markers the edge guard demands of an unsafe method (decision
    5). Used where a test needs a precondition rather than a control's proof
    -- the approvers' standing ahead of the freeze -- and to show a command
    refusing what its control would have refused. */
function postAs(page: Page, url: string, data: object) {
  return page.request.post(url, {
    data,
    headers: {
      "Idempotency-Key": randomUUID(),
      Origin: EDGE_ORIGIN,
      "Sec-Fetch-Site": "same-origin",
      accept: "application/json",
    },
  });
}

function nodeLocator(page: Page, moduleId: string) {
  return page.locator(`button.node[data-node='${moduleId}']`);
}

/** Polls for a node's state over the run API directly, not by trusting the
    open SSE tail to repaint the DOM and not by reloading the page every
    cycle: the real stream stays connected (confirmed against the network
    trace) while the run genuinely progresses server-side, but a live-push
    repaint is not something this journey depends on to prove the run
    finished. An earlier version reloaded the whole page every 2s, which
    opens a fresh `/events` SSE connection per reload -- the API's SSE tail
    holds a connection until `TAIL_DEADLINE` (300s) even after the client has
    navigated away, with nothing checking for an earlier disconnect, so over
    a 320s wait that piled up abandoned connections past the API's own
    `--limit-concurrency 32` (Dockerfile) and answered later requests, in this
    test and the next one, with a bare 503. Polling the JSON directly opens
    and closes one short-lived request per cycle instead, then reloads once
    at the end to sync the DOM for the assertions that follow. */
interface RunRead {
  status: string;
  nodes: { route_node_id: string; module_id: string; state: string }[];
  /** The `run_work` row, absent until the run is enqueued. No section renders
      it, which is why Task 12.5 reads it from the document the browser itself
      holds rather than from a selector -- see that test's own comment. */
  work: { state: string; stop_code: string | null } | null;
}

/** One short-lived read of the run document's `run`, or `undefined` when
    the read was slow, refused or unparsable -- "not yet", never a hang. */
async function readRun(page: Page, caseId: string, runId: string): Promise<RunRead | undefined> {
  try {
    const response = await page.request.get(`/api/v1/cases/${caseId}/run?run=${runId}`, {
      timeout: 10_000,
    });
    if (!response.ok()) return undefined;
    const body = (await response.json()) as { body: { run: RunRead | null } };
    return body.body.run ?? undefined;
  } catch {
    return undefined;
  }
}

async function waitForNode(
  page: Page,
  caseId: string,
  runId: string,
  moduleId: string,
  state: string,
  timeoutMs: number,
): Promise<void> {
  const deadline = Date.now() + timeoutMs;
  let current: string | undefined;
  for (;;) {
    const run = await readRun(page, caseId, runId);
    current = run?.nodes.find((n) => n.module_id === moduleId)?.state;
    if (current === state) break;
    if (Date.now() >= deadline) {
      throw new Error(
        `${moduleId} did not reach ${state} within ${timeoutMs}ms (last: ${current})`,
      );
    }
    await page.waitForTimeout(2_000);
  }
  // Sync the visible DOM once the API confirms the state, retrying the
  // reload itself since a request right after a long wait can still meet a
  // transient 503 while other abandoned connections from this same wait
  // drain.
  await expect(async () => {
    await page.reload({ timeout: 10_000 });
    await expect(nodeLocator(page, moduleId)).toHaveAttribute("data-state", state, {
      timeout: 10_000,
    });
  }).toPass({ timeout: 30_000 });
}

/** Polls the run's own status the way `waitForNode` polls a node's, then
    reloads once so the DOM the assertions read is the state the API confirmed. */
async function waitForRunStatus(
  page: Page,
  caseId: string,
  runId: string,
  status: string,
  timeoutMs: number,
): Promise<void> {
  const deadline = Date.now() + timeoutMs;
  let current: string | undefined;
  for (;;) {
    current = (await readRun(page, caseId, runId))?.status;
    if (current === status) break;
    if (Date.now() >= deadline) {
      throw new Error(`run did not reach ${status} within ${timeoutMs}ms (last: ${current})`);
    }
    await page.waitForTimeout(2_000);
  }
  await expect(async () => {
    await page.reload({ timeout: 10_000 });
    await expect(page.locator("dt:text-is('Status') + dd")).toContainText(status, {
      timeout: 10_000,
    });
  }).toPass({ timeout: 30_000 });
}

/** The receipt of a command that must have been accepted, and the typed
    refusal in the failure when it was not: a bare status comparison says 400
    and not which rule refused, which is the whole of what a reader of a red
    journey needs. The body is the host's `{code, clears}`, never anything a
    document supplied. */
async function receipt<R>(response: APIResponse, status: number): Promise<R> {
  const body = (await response.json()) as R;
  if (response.status() !== status) {
    throw new Error(`refused ${response.status()}: ${JSON.stringify(body)}`);
  }
  return body;
}

